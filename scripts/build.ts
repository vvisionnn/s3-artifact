/** Bundles each action into a single self-contained ESM file for the node24 runtime. */
import { rm } from "node:fs/promises";
import { join, resolve } from "node:path";
import type { BunPlugin } from "bun";

export const ENTRIES = ["upload", "download", "merge"] as const;

/** Routes every `@actions/core` import (including dependencies') to the lightweight shim. */
const coreShim: BunPlugin = {
	name: "actions-core-shim",
	setup(build) {
		build.onResolve({ filter: /^@actions\/core$/ }, () => ({
			path: resolve(import.meta.dir, "../src/shared/core.ts"),
		}));
	},
};

export async function buildAll(outdir: string): Promise<Array<{ entry: string; bytes: number }>> {
	await rm(outdir, { recursive: true, force: true });
	const sizes = [];
	for (const entry of ENTRIES) {
		const result = await Bun.build({
			entrypoints: [resolve(import.meta.dir, `../src/${entry}/index.ts`)],
			outdir: join(outdir, entry),
			target: "node",
			format: "esm",
			plugins: [coreShim],
			banner: "// Generated by `bun run build`. Do not edit.",
		});
		if (!result.success) {
			throw new AggregateError(result.logs, `Build of ${entry} failed`);
		}
		sizes.push({ entry, bytes: result.outputs.reduce((total, output) => total + output.size, 0) });
	}
	return sizes;
}

if (import.meta.main) {
	for (const { entry, bytes } of await buildAll(resolve(import.meta.dir, "../dist"))) {
		console.log(`dist/${entry}/index.js  ${(bytes / 1024).toFixed(0)} KiB`);
	}
}
